// Mechanical "no AI trace" + AI-policy checks. Pure, so test.js can assert them.
const TRACE = /claude|anthropic|co-authored-by|generated with/i;
// authorship markers: always blocked. Bare "claude|anthropic" only counts when the repo isn't about them.
const HARD = /co-authored-by|generated with|🤖|@anthropic\.com|noreply@anthropic/i;
const findTraceT = (topical, ...blobs) => { if (!topical) return findTrace(...blobs); for (const b of blobs) for (const l of String(b || '').split('\n')) if (HARD.test(l)) return l.trim().slice(0, 120); return null; };
const aboutAi = (...texts) => /claude|anthropic/i.test(texts.join('\n'));
const POLICY = /\b(AI|LLMs?|Copilot|ChatGPT|Claude|AI-generated|machine-generated)\b|generated by/;
// text blobs -> first offending line, or null
const findTrace = (...blobs) => { for (const b of blobs) for (const l of String(b || '').split('\n')) if (TRACE.test(l)) return l.trim().slice(0, 120); return null; };
// only added lines of a diff + file names matter; context/removed lines are not ours
const addedLines = (diff) => diff.split('\n').filter(l => l.startsWith('+') && !l.startsWith('+++')).join('\n');
const hasPolicy = (docs) => Object.entries(docs).filter(([, t]) => POLICY.test(t)).map(([f]) => f);
// at most `cap` PRs per repo per 24h (cap 0 = unlimited); `times` = timestamps of PRs already opened
const rateOk = (times, cap, now = Date.now()) => !cap || (times || []).filter(t => now - t < 864e5).length < cap;
// last line-leading JSON object of a model answer (the object may nest, so not lastIndexOf('{'))
const lastJson = (raw) => JSON.parse(raw.slice(raw.lastIndexOf('\n{') + 1 || raw.indexOf('{')));
const prBlocked = (j) => !j.permissions?.push && j.pull_request_creation_policy === 'collaborators_only';
module.exports = { lastJson, prBlocked, findTraceT, aboutAi, findTrace, addedLines, hasPolicy, rateOk };
